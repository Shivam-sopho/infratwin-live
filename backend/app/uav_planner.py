"""Occlusion-adaptive UAV view planning (Local View-Angle Adaptation, "Algorithm 2").

The inspection target (a defect region on a component face) is sampled as a grid of surface
points. Candidate camera poses are generated by rotating the face normal through yaw/pitch offsets
at a given standoff. Each candidate is scored by the fraction of target points it can see (line of
sight not blocked by any other structure or occluder, incidence below a limit) weighted by viewing
obliquity. Flight paths between poses are checked against clearance-inflated obstacles, with
detours inserted around blocked segments.
"""

import math

import numpy as np
from pydantic import BaseModel

from .models import Asset, Component, Geometry

MAX_INCIDENCE_DEG = 65.0
CLEARANCE_M = 1.0
MIN_ALTITUDE_M = 1.0  # stay above water / ground
GRID_N = 10


class Viewpoint(BaseModel):
    id: str
    yaw_deg: float
    pitch_deg: float
    standoff_m: float
    position: tuple[float, float, float]
    look_at: tuple[float, float, float]
    coverage: float  # fraction of target points visible
    mean_incidence_deg: float | None
    quality: float  # coverage weighted by cos(incidence)
    blocked_by: list[str]  # occluders/components that block at least one target point


class FlightPath(BaseModel):
    waypoints: list[tuple[float, float, float]]
    length_m: float
    detours: int


class Box:
    """Axis-aligned bounding box of a primitive."""

    def __init__(self, id: str, name: str, lo: np.ndarray, hi: np.ndarray):
        self.id, self.name, self.lo, self.hi = id, name, lo, hi

    def inflated(self, m: float) -> "Box":
        return Box(self.id, self.name, self.lo - m, self.hi + m)

    def contains(self, p: np.ndarray) -> bool:
        return bool(np.all(p >= self.lo) and np.all(p <= self.hi))


def box_of(id: str, name: str, g: Geometry) -> Box:
    c = np.array(g.position, dtype=float)
    if g.shape == "box":
        half = np.array(g.size, dtype=float) / 2
    elif g.shape == "cylinder":
        half = np.array([g.size[0], g.size[1] / 2, g.size[0]], dtype=float)
    elif g.shape == "arch_rib":  # parabolic rib springing at `position`
        span, rise, thick = g.size
        return Box(id, name, c + np.array([-span / 2, 0, -thick / 2]), c + np.array([span / 2, rise, thick / 2]))
    else:  # arch: half-cylinder shell, axis along z
        r, length = g.size[0], g.size[1]
        return Box(id, name, c + np.array([-r, 0, -length / 2]), c + np.array([r, r, length / 2]))
    return Box(id, name, c - half, c + half)


def obstacles_for(asset: Asset, exclude: str | None = None) -> list[Box]:
    out = [box_of(c.id, c.name, c.geometry) for c in asset.components if c.geometry and c.id != exclude]
    out += [box_of(o.id, o.name, o.geometry) for o in asset.occluders]
    return out


def segments_hit(a: np.ndarray, b: np.ndarray, box: Box) -> np.ndarray:
    """Slab test: which segments a[i]→b[i] intersect the box (vectorised over i)."""
    d = b - a
    with np.errstate(divide="ignore", invalid="ignore"):
        inv = 1.0 / d
        t1 = (box.lo - a) * inv
        t2 = (box.hi - a) * inv
    tmin = np.nanmax(np.minimum(t1, t2), axis=-1)
    tmax = np.nanmin(np.maximum(t1, t2), axis=-1)
    # Parallel to a slab and outside it -> miss.
    outside = (np.abs(d) < 1e-12) & ((a < box.lo) | (a > box.hi))
    return (tmax >= np.maximum(tmin, 0.0)) & (tmin <= 1.0) & ~outside.any(axis=-1)


def target_points(comp: Component, bbox_uv: tuple[float, float, float, float] | None, n: int = GRID_N):
    """Grid of points on the component's front (+z) face, optionally restricted to a finding's region."""
    g = comp.geometry
    assert g is not None and g.shape in ("box", "cylinder")
    cx, cy, cz = g.position
    w, h, d = g.size if g.shape == "box" else (g.size[0] * 2, g.size[1], g.size[0] * 2)
    u1, v1, u2, v2 = bbox_uv or (0.0, 0.0, 1.0, 1.0)
    # Pad small regions so the grid samples the defect's surroundings too.
    pu, pv = max(0.0, 0.08 - (u2 - u1) / 2), max(0.0, 0.08 - (v2 - v1) / 2)
    u1, u2, v1, v2 = max(0, u1 - pu), min(1, u2 + pu), max(0, v1 - pv), min(1, v2 + pv)
    us, vs = np.meshgrid(np.linspace(u1, u2, n), np.linspace(v1, v2, n))
    pts = np.stack([cx + (us - 0.5) * w, cy + (0.5 - vs) * h, np.full_like(us, cz + d / 2)], -1).reshape(-1, 3)
    return pts, np.array([0.0, 0.0, 1.0])


def _direction(normal: np.ndarray, yaw_deg: float, pitch_deg: float) -> np.ndarray:
    """Rotate the face normal by yaw (about +y) then pitch (towards +y)."""
    yaw, pitch = math.radians(yaw_deg), math.radians(pitch_deg)
    # Normal is +z for front faces: yaw swings toward ±x, pitch lifts toward +y.
    v = np.array([math.sin(yaw) * math.cos(pitch), math.sin(pitch), math.cos(yaw) * math.cos(pitch)])
    if not np.allclose(normal, [0, 0, 1]):
        raise ValueError("only +z faces supported")
    return v


def evaluate(cam: np.ndarray, pts: np.ndarray, normal: np.ndarray, obstacles: list[Box]) -> tuple[np.ndarray, np.ndarray, set[str]]:
    """Per-point visibility and incidence for a camera position."""
    to_cam = cam - pts
    dist = np.linalg.norm(to_cam, axis=1)
    inc = np.degrees(np.arccos(np.clip((to_cam @ normal) / dist, -1, 1)))
    # Start the ray a hair off the surface so the target face itself never blocks.
    start = pts + to_cam / dist[:, None] * 0.05
    visible = inc < MAX_INCIDENCE_DEG
    blockers: set[str] = set()
    for box in obstacles:
        hit = segments_hit(start, np.broadcast_to(cam, start.shape), box)
        if hit.any():
            blockers.add(box.name)
        visible &= ~hit
    return visible, inc, blockers


def score_viewpoints(
    asset: Asset,
    comp: Component,
    bbox_uv: tuple[float, float, float, float] | None,
    standoff_m: float = 6.0,
    max_yaw_deg: float = 60.0,
    max_pitch_deg: float = 40.0,
    step_deg: float = 10.0,
) -> tuple[Viewpoint, list[Viewpoint]]:
    """(baseline square-on viewpoint, candidates sorted best-first)."""
    pts, normal = target_points(comp, bbox_uv)
    centre = pts.mean(axis=0)
    obstacles = obstacles_for(asset, exclude=comp.id)
    safety = [b.inflated(CLEARANCE_M) for b in obstacles + [box_of(comp.id, comp.name, comp.geometry)]]

    def make(yaw: float, pitch: float, idx: str) -> Viewpoint | None:
        cam = centre + _direction(normal, yaw, pitch) * standoff_m
        if cam[1] < MIN_ALTITUDE_M or any(b.contains(cam) for b in safety):
            return None
        vis, inc, blockers = evaluate(cam, pts, normal, obstacles)
        cov = float(vis.mean())
        mean_inc = float(inc[vis].mean()) if vis.any() else None
        quality = float((vis * np.cos(np.radians(np.minimum(inc, 90)))).mean())
        return Viewpoint(
            id=idx,
            yaw_deg=yaw,
            pitch_deg=pitch,
            standoff_m=standoff_m,
            position=tuple(round(float(x), 3) for x in cam),
            look_at=tuple(round(float(x), 3) for x in centre),
            coverage=round(cov, 3),
            mean_incidence_deg=round(mean_inc, 1) if mean_inc is not None else None,
            quality=round(quality, 3),
            blocked_by=sorted(blockers),
        )

    baseline = make(0.0, 0.0, "baseline")
    if baseline is None:  # square-on pose itself is inside an obstacle's clearance
        cam = centre + normal * standoff_m
        vis, inc, blockers = evaluate(cam, pts, normal, obstacles)
        baseline = Viewpoint(
            id="baseline", yaw_deg=0, pitch_deg=0, standoff_m=standoff_m,
            position=tuple(float(x) for x in cam), look_at=tuple(float(x) for x in centre),
            coverage=round(float(vis.mean()), 3), mean_incidence_deg=None, quality=0.0, blocked_by=sorted(blockers),
        )

    cands = []
    yaws = np.arange(-max_yaw_deg, max_yaw_deg + 1e-6, step_deg)
    pitches = np.arange(-max_pitch_deg, max_pitch_deg + 1e-6, step_deg)
    for yaw in yaws:
        for pitch in pitches:
            vp = make(float(yaw), float(pitch), f"s{standoff_m:g}_y{yaw:+.0f}_p{pitch:+.0f}")
            if vp is not None:
                cands.append(vp)
    cands.sort(key=lambda v: (v.quality, v.coverage), reverse=True)
    return baseline, cands


def _clear(a: np.ndarray, b: np.ndarray, safety: list[Box]) -> bool:
    return not any(segments_hit(a[None], b[None], box)[0] for box in safety)


def plan_flight(asset: Asset, viewpoints: list[Viewpoint], home: tuple[float, float, float] | None = None) -> FlightPath:
    """Home → each viewpoint → home, inserting detour waypoints around clearance-inflated obstacles."""
    safety = [b.inflated(CLEARANCE_M) for b in obstacles_for(asset)]
    start = np.array(home or asset.uav_home or (0.0, 5.0, 30.0), dtype=float)
    stops = [start] + [np.array(v.position, dtype=float) for v in viewpoints] + [start]
    path = [stops[0]]
    detours = 0
    for a, b in zip(stops, stops[1:]):
        if _clear(a, b, safety):
            path.append(b)
            continue
        # Single intermediate waypoint: search offsets out (+z), up and sideways; keep the shortest clear detour.
        mid = (a + b) / 2
        best, best_len = None, math.inf
        for dx in (0.0, -6.0, 6.0, -12.0, 12.0, -20.0, 20.0):
            for dy in (0.0, 3.0, 6.0, 9.0, 12.0):
                for dz in (0.0, 3.0, 6.0, 9.0, 12.0):
                    w = mid + np.array([dx, dy, dz])
                    extra = float(np.linalg.norm(w - a) + np.linalg.norm(b - w))
                    if extra < best_len and w[1] >= MIN_ALTITUDE_M and _clear(a, w, safety) and _clear(w, b, safety):
                        best, best_len = w, extra
        if best is None:
            raise ValueError("no collision-free route found between waypoints")
        path += [best, b]
        detours += 1
    pts = np.array(path)
    length = float(np.linalg.norm(np.diff(pts, axis=0), axis=1).sum())
    return FlightPath(
        waypoints=[tuple(round(float(x), 3) for x in p) for p in pts], length_m=round(length, 1), detours=detours
    )
